def 美化(模式: str) -> str:
    """把语法糖的正则粗略变成"人话写法"，只求看得懂，不求可逆"""
    文本 = 模式
    文本 = re.sub(r'^\^', '', 文本)
    文本 = 文本.replace(r'(?P<缩进>[ \t]*)', '')
    文本 = 文本.replace(r'\s*', ' ').replace(r'\s+', ' ')
    文本 = re.sub(r'\[:：\]\?', ':', 文本)
    文本 = re.sub(r'\[ \\t\]\*', '', 文本)
    文本 = 文本.replace(r'$', '')
    def 抓组(m):
        return '«' + m.group(1) + '»'
    文本 = re.sub(r'\(\?P<([^>]+)>.*?\)(?=[^)]|$)', 抓组, 文本)
    文本 = re.sub(r'\(\?:([^()]*)\)', r'\1', 文本)
    文本 = 文本.replace('?:', '')
    文本 = 文本.replace('|', ' / ')
    文本 = re.sub(r'\\', '', 文本)
    # 字符类噪音：[:：] → ：；[（(]? / [)）]? 这类可选括号直接清掉
    文本 = re.sub(r'\[\s*:：\s*\]', '：', 文本)
    文本 = re.sub(r'\[（\(\]\?', '', 文本)
    文本 = re.sub(r'\[\)）\]\?', '', 文本)
    文本 = 文本.replace(' ?', ' ')
    文本 = 文本.replace('?', '')          # 剩下的 ? 都是"可选"标记
    文本 = re.sub(r'\s+', ' ', 文本).strip()
    文本 = 文本.replace('::', '：').replace(':：', '：')
    文本 = 文本.replace(' ：', '：')
    if not 文本.endswith((':', '：')):
        文本 += '：'
    return 文本


def 表(标题: str, 映射: dict[str, str], 说明: str = '') -> str:
    行 = [f'### {标题}', '']
    if 说明:
        行 += [说明, '']
    行 += ['| 桥语言 | Python |', '| --- | --- |']
    for 中, 英 in 映射.items():
        行.append(f'| `{中}` | `{英}` |')
    行.append('')
    return '\n'.join(行)


def 反查同义(映射: dict[str, str]) -> str:
    """把同一个英文目标的多个中文写法并成一行"""
    组: dict[str, list[str]] = {}
    for 中, 英 in 映射.items():
        组.setdefault(英, []).append(中)
    行 = ['| Python | 桥语言写法（任选） |', '| --- | --- |']
    for 英, 中们 in 组.items():
        行.append(f'| `{英}` | ' + ' / '.join(f'`{x}`' for x in 中们) + ' |')
    return '\n'.join(行) + '\n'


