# 04 函数：定义 / 参数 / 默认值 / 返回 / 多返回值
# 对照文件：手打同名 .bridge，第 1 行起逐行对应

def 加法(a, b):
    return a + b

def 问候(名字, 前缀="你好"):
    return 前缀 + "，" + 名字

def 极值(数据):
    return max(数据), min(数据)

def 累加(数据, 起始=0):
    合计 = 起始
    for 值 in 数据:
        合计 = 合计 + 值
    return 合计

def 无返回():
    print("这句话来自 无返回")

print("加法：", 加法(2, 3))
print("问候：", 问候("爸爸"))
print("问候：", 问候(前缀="早上好", 名字="桥语言"))
大, 小 = 极值([3, 1, 4, 1, 5])
print("最大：", 大, "最小：", 小)
print("累加：", 累加([1, 2, 3]), 累加([1, 2, 3], 10))
无返回()
