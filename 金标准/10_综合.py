成绩 = {"语文": 90, "数学": 85, "英语": 78}

def 总分(成绩表):
    合计 = 0
    for 科目 in 成绩表:
        合计 = 合计 + 成绩表[科目]
    return 合计

def 评级(分数):
    if 分数 >= 90:
        return "优秀"
    elif 分数 >= 70:
        return "良好"
    else:
        return "待提升"

总计 = 总分(成绩)
平均分 = 总计 / len(成绩)

print("成绩单：", 成绩)
print("总分：", 总计)
print("平均分：", 平均分)
print("评级：", 评级(平均分))

for 科目, 分数 in 成绩.items():
    print(科目, "：", 分数, "→", 评级(分数))
