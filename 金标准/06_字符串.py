# 06 字符串：引号 / 拼接 / 长度 / 包含 / 替换 / 拆分 / 类型转换
# 对照文件：手打同名 .bridge，第 1 行起逐行对应

问候 = "你好，世界！"
名字 = "爸爸"

print(问候)
print(名字 + "，欢迎")
print("长度：", len(问候))
print("包含：", "世界" in 问候)
print("替换：", 问候.replace("世界", "桥语言"))
print("大写：", "abc".upper())
print("去空白：", "  两侧空格  ".strip())

句子 = "以逗号,分隔,的文本"
print("拆分：", 句子.split(","))
print("数字：", int("42") + 1, float("1.5") * 2)
print("格式化：", "我叫%s，今年%d岁" % (名字, 18))
