# 对照文件：手打同名 .bridge，第 1 行起逐行对应

分数 = 86
等级 = ""

if 分数 >= 90:
    等级 = "优秀"
elif 分数 >= 60:
    等级 = "及格"
else:
    等级 = "不及格"
print("分数：", 分数, "等级：", 等级)

成年 = 分数 > 18
if 成年 and not 分数 < 0:
    print("逻辑：并且 + 不是 命中")
if 成年 or 分数 > 100:
    print("逻辑：或者 命中")

if 分数 == 86:
    print("比较：等于 命中")
if 分数 != 100:
    print("比较：不等于 命中")
if 等级 is not None:
    print("比较：是 不是 空 命中")
