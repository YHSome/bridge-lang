"""规则体检：把"手工堆出来的规则表"里潜伏的矛盾翻出来

规则表是一堆纯数据、由很多文件拼起来，加词很容易，但**冲突往往不会立刻报错**：

- 两条语法糖都能匹配同一行，谁先谁赢——用户看到的是"有时候生效有时候不生效"；
- 糖的模板里写了 `{次数}`，但正则里没有 `(?P<次数>…)` 这个组——运行时才炸；
- 糖没有 `^…$` 整行锚定——会在行中间乱改；
- 关键字别名映射到一个既不是 Python 关键字、也不是运算符的东西。

`体检()` 把这些都扫一遍，分三级：

    错误  一定会出错（模板占位符缺失、映射值非法、键不在词表里）
    警告  可能出事（糖没整行锚定、两条糖锚点相同）
    提示  不是错，但你该知道（单字别名、模块别名占用了常见词）
"""

from __future__ import annotations

import keyword
import re

_合法运算符 = {'==', '!=', '<=', '>=', '<', '>', '+', '-', '*', '/', '%', '//', '**',
               '&', '|', '^', '~', '<<', '>>', ':='}
_占位 = re.compile(r'\{(\w+)\}')


def _糖锚点(模式: str) -> str:
    """抓糖正则开头的字面汉字/字母（用来判"两条糖是不是同一个引导词"）"""
    文 = 模式[1:] if 模式.startswith('^') else 模式
    文 = 文.lstrip()
    if 文.startswith('(?P<缩进>'):
        结束 = 文.find(')')
        文 = 文[结束 + 1:] if 结束 >= 0 else ''
    匹配 = re.match(r'([A-Za-z\u3400-\u9fff]+)', 文)
    return 匹配.group(1) if 匹配 else ''


def 体检(规则: dict) -> list[dict]:
    结果: list[dict] = []

    def 记(级别: str, 项目: str, 说明: str) -> None:
        结果.append({'级别': 级别, '项目': 项目, '说明': 说明})

    # ---- 1. 关键字映射值合法性（是不是真的 Python 关键字/运算符）----
    for 中文, 英文 in (规则.get('关键字') or {}).items():
        if not isinstance(英文, str):
            记('错误', f'关键字.{中文}', f'映射值不是字符串：{英文!r}')
            continue
        合法 = (keyword.iskeyword(英文) or 英文 in _合法运算符
            or 英文 in ('True', 'False', 'None', 'match', 'case'))  # 软关键字
        if not 合法:
            记('错误', f'关键字.{中文}', f'映射到 {英文!r}，既不是 Python 关键字也不是运算符')

    # ---- 2. 值位置 / 助词的键必须也在词表里，否则语义对不上 ----
    for 表名, 基准 in (('值位置', '词表'), ('助词', '词表')):
        表 = 规则.get(表名) or {}
        if not 表:
            continue
        for 键 in 表:
            if 表名 == '值位置' and 键 not in (规则.get('词表') or {}):
                记('警告', f'{表名}.{键}', '这个词不在词表里，值位置特例永远不会生效')

    # ---- 3. 语法糖：模板占位符 vs 正则命名组 ----
    糖们 = 规则.get('语法糖') or []
    for 序, (模式, 模板) in enumerate(糖们, 1):
        题目 = f'语法糖#{序}'
        try:
            编译 = re.compile(模式)
        except re.error as 错误:
            记('错误', 题目, f'正则写坏了：{错误}')
            continue
        组名 = set(编译.groupindex)
        用到的 = set(_占位.findall(模板))
        缺 = 用到的 - 组名
        if 缺:
            记('错误', 题目, f'模板用了 {sorted(缺)}，但正则里没有这些命名组（运行时会炸）')
        多余 = 组名 - 用到的 - {'缩进'}
        if 多余:
            记('提示', 题目, f'正则里定义了但模板没用的组：{sorted(多余)}')
        if not 模式.startswith('^') or not 模式.endswith('$'):
            记('警告', 题目, '没有整行锚定（^…$），可能在行中间误改')
        if '缩进' not in 组名 and '{缩进}' not in 模板:
            记('警告', 题目, '没有处理缩进：嵌套块里的糖会把缩进丢掉')

    # ---- 4. 语法糖锚点重叠：同一个引导词，或一个词是另一个的前缀 ----
    按锚点: dict[str, list[int]] = {}
    for 序, (模式, _模板) in enumerate(糖们, 1):
        锚 = _糖锚点(模式)
        if 锚:
            按锚点.setdefault(锚, []).append(序)
    for 锚, 序号们 in 按锚点.items():
        if len(序号们) > 1:
            记('提示', f'锚点「{锚}」', f'语法糖 #{序号们} 都以它开头，先写的先匹配')
    锚词们 = sorted(按锚点)
    for 短 in 锚词们:
        for 长 in 锚词们:
            if 短 == 长 or not 长.startswith(短):
                continue
            # 长的在前才安全（先匹配更具体的）；短的在前面就会把长的抢走
            if 按锚点[短][0] < 按锚点[长][0]:
                记('提示', f'锚点「{短}」⊂「{长}」',
                   f'#{按锚点[短]} 排在 #{按锚点[长]} 前面，短规则可能先抢走长规则的句子')

    # ---- 5. 单字别名 / 模块别名：不是错，但要知道它占了词 ----
    单字 = sorted(词 for 词 in (规则.get('关键字') or {}) if len(词) == 1)
    if 单字:
        记('提示', '单字关键字', f'{len(单字)} 个：{"、".join(单字)}（容易和变量名撞）')
    模块们 = sorted((规则.get('模块') or {}))
    if 模块们:
        记('提示', '模块别名', f'{"、".join(模块们)}（这些词不能再当变量名）')

    # ---- 6. 方法名和内建名重名：允许，但语义按位置分 ----
    重名 = sorted(set(规则.get('方法') or {}) & set(规则.get('内建') or {}))
    if 重名:
        记('提示', '内建/方法重名', f'{"、".join(重名)}（点号后是方法、光写是内建，属正常）')

    return 结果


def 统计(结果: list[dict]) -> dict[str, int]:
    计数 = {'错误': 0, '警告': 0, '提示': 0}
    for 项 in 结果:
        计数[项['级别']] = 计数.get(项['级别'], 0) + 1
    return 计数
