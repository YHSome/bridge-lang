"""脚手架：`桥 init` 一键生成一个能跑的 .bridge 起步工程

生成三个文件（不覆盖已有文件，除非 `-f`）：

    主程序.bridge   入口：导入模块、定义函数、分支、循环、语法糖各来一段
    工具.bridge     被主程序导入的小模块
    README.md       三行启动 + 语法速查

为什么不做成"新建项目工程"（pyproject/Cargo 那套）：桥语言是 Python 的超集，
用户往往是在**已有的 Python 项目里加几个 .bridge 文件**，而不是从零建工程。
所以脚手架只给"最小可跑的一套"，不替代原有工程结构。
"""

from __future__ import annotations

from pathlib import Path

主程序 = '''# 桥语言起步工程 —— 改这个文件就能跑
# 运行（在桥语言目录下执行）：
#   python 桥.py 运行 主程序.bridge

导入 工具

定义 打招呼(名字: 字符串) -> 字符串:
    返回 f"你好，{名字}"

对于 名字 在 【"爸爸"， "同学"】:
    输出（打招呼(名字))

分数 = 95
如果 分数 至少 90 那么:
    输出（"等级：", "优秀"）
否则的话:
    输出（"等级：", "及格"）

重复执行（2）次:
    输出（工具.口号()）

# 英文原名照样能用（.bridge 是 Python 的超集）
print("这一行是原生 Python")
'''

工具 = '''"""被 主程序 导入的小模块（.bridge 文件之间可以直接 导入）。"""

版本 = "0.1"


定义 口号() -> 字符串:
    返回 "桥语言：中文也能写程序"
'''

说明 = '''# 我的桥语言项目

这是 `桥 init` 生成的起步工程。

## 三行启动

```bash
python 桥.py 运行 主程序.bridge    # 跑起来
python 桥.py repl                # 想试一句就试一句
python 桥.py 查看 主程序.bridge    # 看它被翻成了什么 Python
```

> 上面的 `桥.py` 指桥语言本体所在目录。如果你已经在桥语言目录里，直接照抄即可；
> 否则把路径换成完整的，例如 `python D:/bridge/桥.py 运行 主程序.bridge`。

## 语法速查

| 想写 | 就写 |
| --- | --- |
| 定义函数 | `定义 名字(参数):` + `返回 …` |
| 条件 | `如果 条件 那么:` / `否则如果 条件 那么:` / `否则的话:` |
| 循环 | `对于 x 在 序列:` · `当 条件:` · `重复执行（3）次:` |
| 赋值 | `x = 1` · `设 x 为 1` · `将 x 增加 1` |
| 输出 | `输出（…）` 或 `输出 …`（裸写也行） |
| 异常 | `尝试执行:` / `捕获 值错误 时:` / `无论如何:` |
| 导入 | `导入 数学` · `导入 json`（英文模块名照样能用） |
| 查词 | `python 桥.py 查 长度` |

完整对照表见桥语言的 `README.md` 第三、四章；写错了也别怕，报错会告诉你
「你是不是想写 X」（`转译器/诊断.py`）。

## 注意

- 规则表里的词是**保留字**（如 `时间`、`排序`、`长度`），别拿它们当变量名——
  `python 桥.py 规则` 能列出全部被占用的词；
- 想用编辑器：双击桥语言目录里的 `桥编辑器.pyw`，F5 运行、Ctrl+Enter 试跑选区。
'''

_文件们 = {'主程序.bridge': 主程序, '工具.bridge': 工具, 'README.md': 说明}


def 初始化(目标目录: str | Path, *, 覆盖: bool = False) -> dict:
    """生成起步工程，返回 {'目录': …, '文件': [...]}"""
    目录 = Path(目标目录)
    目录 = 目录.resolve() if 目录.exists() else 目录
    已存在 = [名 for 名 in _文件们 if (目录 / 名).exists()]
    if 已存在 and not 覆盖:
        raise FileExistsError(f'这些文件已经存在：{"、".join(已存在)}')
    目录.mkdir(parents=True, exist_ok=True)
    for 名, 内容 in _文件们.items():
        (目录 / 名).write_text(内容, encoding='utf-8')
    return {'目录': str(目录), '文件': list(_文件们)}
