r"""语法糖：整行重写，把中文语序直接变成一行标准 Python

**这是让桥语言"读起来像中文"的主力机制。** 一条糖 = (正则, 模板)：

- 正则**必须整行匹配**（`^` … `$`），用命名捕获组 `(?P<名字>...)` 抓变量；
- 模板里写 `{名字}`，引擎会自动换成正则的 `\g<名字>`；
- **一行进、一行出**，行号永远不变，所以金标准逐行 diff 照样能对；
- 缩进必须用 `{缩进}` 带回去，否则嵌套就废了。

执行顺序很关键：**糖在"词替换"之前跑**。所以这里的正则写的是**中文原词**
（`如果` / `对于` / `捕获` / `重复执行`），模板直接吐出英文关键字；
捕获组里的表达式（比如 `求长度(数据)`）会在随后的词替换里继续被翻译。

    ┌ 归一 → 成员 → 方法 → 语法糖 → 词替换 → 助词 ┐
    └ 糖拿到的还是中文；糖吐出来的英文不会被再翻回去 ┘

加糖的安全线（违反就别加）：

1. 只匹配整行，别匹配行中间——否则会跟表达式打架；
2. 中文关键词后面要有**唯一锚点词**（`次`、`每个`、`中的`、`那么`、`时`），否则歧义；
3. 产物必须是**合法的单行语句**，不能凭空生出多行（那会破坏行号映射）；
4. 字符串、注释里的内容不参与（引擎只处理代码段）。
"""

语法糖 = [
    # ---------------- 循环 ----------------
    # 顺序原则：**更具体的放前面**（长锚点优先），否则短的会把长的句子抢走。
    # 这条是 `桥 体检` 扫出来的：重复执行直到 曾经排在 重复 后面。
    # 重复执行直到 条件:  →  while not 条件:（Scratch 的"重复执行直到"）
    (r'^(?P<缩进>[ \t]*)重复执行直到\s+(?P<条件>\S.*?)\s*[:：]?\s*$',
     '{缩进}while not ({条件}):'),
    # 重复执行（3）次:  /  重复 3 次:  /  重复执行3次:
    (r'^(?P<缩进>[ \t]*)重复执行\s*[（(]?\s*(?P<次数>.+?)\s*[)）]?\s*次\s*[:：]\s*$',
     '{缩进}for _ in range({次数}):'),
    (r'^(?P<缩进>[ \t]*)重复\s*[（(]?\s*(?P<次数>.+?)\s*[)）]?\s*次\s*[:：]\s*$',
     '{缩进}for _ in range({次数}):'),
    # 永久循环:  /  死循环:
    (r'^(?P<缩进>[ \t]*)(?:永久循环|死循环)\s*[:：]\s*$', '{缩进}while True:'),
    # 只要 条件 就重复:  →  while 条件:
    (r'^(?P<缩进>[ \t]*)只要\s+(?P<条件>\S.*?)\s*就重复\s*[:：]\s*$', '{缩进}while {条件}:'),
    # 对于 每个 x 在 序列:  →  for x in 序列:
    (r'^(?P<缩进>[ \t]*)对于\s*每个\s*(?P<变量>[^\s:：]+)\s*在\s*(?P<序列>\S.*?)\s*[:：]\s*$',
     '{缩进}for {变量} in {序列}:'),
    # 遍历 序列 中的 每个 x:  →  for x in 序列:
    (r'^(?P<缩进>[ \t]*)遍历\s*(?P<序列>\S.*?)\s*中的\s*每个\s*(?P<变量>[^\s:：]+)\s*[:：]\s*$',
     '{缩进}for {变量} in {序列}:'),
    # 对 序列 中的每一项:  →  for _ in 序列:
    (r'^(?P<缩进>[ \t]*)对\s*(?P<序列>\S.*?)\s*中的每一项\s*[:：]\s*$', '{缩进}for _ in {序列}:'),

    # ---------------- 主程序入口 ----------------
    # 当前是主程序:  /  如果 当前是主程序:  →  if __name__ == "__main__":
    # 中文语序里常写成「如果 当前是主程序:」，所以如果也一起吃掉。
    (r'^(?P<缩进>[ \t]*)(?:如果\s+)?当前是主程序\s*(?:的话|那么|则)?\s*[:：]\s*$',
     '{缩进}if __name__ == "__main__":'),

    # ---------------- 分支 ----------------
    # 如果 条件 那么:  →  if 条件:
    (r'^(?P<缩进>[ \t]*)如果\s+(?P<条件>\S.*?)\s*(?:那么|则)\s*[:：]\s*$', '{缩进}if {条件}:'),
    # 否则如果 条件 那么:  →  elif 条件:
    (r'^(?P<缩进>[ \t]*)否则如果\s+(?P<条件>\S.*?)\s*(?:那么|则)\s*[:：]\s*$', '{缩进}elif {条件}:'),
    # 否则的话:  →  else:
    (r'^(?P<缩进>[ \t]*)否则\s*(?:的话)?\s*[:：]\s*$', '{缩进}else:'),

    # ---------------- 定义 ----------------
    # 定义函数 名(参数):  →  def 名(参数):
    (r'^(?P<缩进>[ \t]*)定义函数\s*(?P<名>[^\s(（:：]+)\s*(?P<参数>[（(].*[)）])\s*[:：]\s*$',
     '{缩进}def {名}{参数}:'),

    # ---------------- 异常 ----------------
    # 尝试执行:  →  try:
    (r'^(?P<缩进>[ \t]*)尝试执行\s*[:：]\s*$', '{缩进}try:'),
    # 无论如何:  →  finally:
    (r'^(?P<缩进>[ \t]*)无论如何\s*[:：]\s*$', '{缩进}finally:'),
    # 捕获异常时:  →  except:
    (r'^(?P<缩进>[ \t]*)捕获异常时\s*[:：]\s*$', '{缩进}except:'),
    # 捕获 值错误 时:  →  except 值错误:   （值错误 随后被词替换成 ValueError）
    (r'^(?P<缩进>[ \t]*)捕获\s+(?P<类型>\S.*?)\s*时\s*[:：]\s*$', '{缩进}except {类型}:'),

    # ---------------- 流程 ----------------
    (r'^(?P<缩进>[ \t]*)跳出循环\s*$', '{缩进}break'),
    (r'^(?P<缩进>[ \t]*)继续下一次循环\s*$', '{缩进}continue'),
    (r'^(?P<缩进>[ \t]*)(?:结束本次循环|进入下一次循环)\s*$', '{缩进}continue'),
    # 直到 条件 为止:  →  while not 条件:
    (r'^(?P<缩进>[ \t]*)直到\s+(?P<条件>\S.*?)\s*为止\s*[:：]?\s*$',
     '{缩进}while not ({条件}):'),
    # 一直重复:  →  while True:（Scratch 的"一直重复"积木）
    (r'^(?P<缩进>[ \t]*)(?:一直重复|一直循环)\s*[:：]?\s*$', '{缩进}while True:'),
    # 等待 条件 直到:  →  while not 条件: pass
    (r'^(?P<缩进>[ \t]*)等待\s+(?P<条件>\S.*?)\s*直到\s*[:：]?\s*$',
     '{缩进}while not ({条件}): pass'),
    # 当 条件 就 做什么:  →  while 条件:（"就"当锚点，避免和助词抢）
    (r'^(?P<缩进>[ \t]*)当\s+(?P<条件>\S.*?)\s+就\s+(?P<语句>.+)$',
     '{缩进}while {条件}: {语句}'),

    # ---------------- 单行叙述 ----------------
    # 如果 条件 就 语句  →  if 条件: 语句      （单行 if，不用缩进块）
    (r'^(?P<缩进>[ \t]*)如果\s+(?P<条件>\S.*?)\s+就\s+(?P<语句>.+)$',
     '{缩进}if {条件}: {语句}'),
    # 否则 语句  →  else: 语句
    (r'^(?P<缩进>[ \t]*)否则\s+(?P<语句>.+)$', '{缩进}else: {语句}'),
    # 把 目标 设为 值  →  目标 = 值
    (r'^(?P<缩进>[ \t]*)把\s+(?P<目标>[^\s，,]+)\s+(?:设为|设定为|赋值成)\s+(?P<值>.+)$',
     '{缩进}{目标} = {值}'),
    # Scratch 式的三种赋值语序，全都认
    (r'^(?P<缩进>[ \t]*)设\s+(?P<目标>[^\s，,]+)\s+为\s+(?P<值>.+)$', '{缩进}{目标} = {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+(?:设为|设定为)\s+(?P<值>.+)$',
     '{缩进}{目标} = {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+增加\s+(?P<值>.+)$', '{缩进}{目标} += {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+减少\s+(?P<值>.+)$', '{缩进}{目标} -= {值}'),
    # 将 目标 乘以/除以/取模/乘方/整除商 值  →  复合赋值
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+乘以\s+(?P<值>.+)$',
     '{缩进}{目标} *= {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+除以\s+(?P<值>.+)$',
     '{缩进}{目标} /= {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+取模\s+(?P<值>.+)$',
     '{缩进}{目标} %= {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+乘方\s+(?P<值>.+)$',
     '{缩进}{目标} **= {值}'),
    (r'^(?P<缩进>[ \t]*)将\s+(?P<目标>[^\s，,]+)\s+整除商\s+(?P<值>.+)$',
     '{缩进}{目标} //= {值}'),
    # 给 目标 加上/减去/乘以/除以 值  →  目标 += 值
    (r'^(?P<缩进>[ \t]*)给\s+(?P<目标>[^\s，,]+)\s+加上\s+(?P<值>.+)$', '{缩进}{目标} += {值}'),
    (r'^(?P<缩进>[ \t]*)给\s+(?P<目标>[^\s，,]+)\s+减去\s+(?P<值>.+)$', '{缩进}{目标} -= {值}'),
    # 输出 值  →  print(值)   （有括号的写法走词表，这里只管"裸写"）
    (r'^(?P<缩进>[ \t]*)(?:输出|打印)\s+(?P<参数>[^\s(（].*)$', '{缩进}print({参数})'),
]
