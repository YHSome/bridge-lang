"""规则包

**规则模块的契约（写新规则文件时照着抄）**

每个 `规则/*.py` 只需要在模块顶层定义若干张表，键 = 方言写法，值 = Python 写法：

    关键字 = {'如果': 'if', ...}          # 保留字，只允许全等匹配
    内建   = {'打印': 'print', ...}       # 内建函数/类型名
    异常   = {'值错误': 'ValueError', ...} # 异常类名
    标点   = {'（': '(', '　': '    ', ...} # 全角 → 半角（字符级 translate）
    模块   = {'数学': 'math', ...}         # 中文模块名 → 真实模块名
    成员   = {'数学': {'圆周率': 'pi', ...}} # 中文模块下的属性/函数名

要点：

1. 表名固定，`规则加载.py` 靠 `getattr` 扫描，不需要注册、不需要 import 改代码；
2. 同名键在不同文件里取值冲突时，加载阶段直接报 `规则冲突`，不会静默覆盖；
3. 一行一张表，返回结果里 `规则清单()` 能看出每条规则来自哪个文件；
4. 新增一类规则（比如「中文运算符」「库别名」）→ 在这四个表名之外加表名，
   同时到 `规则加载.py` 的 `表名` 元组里登记即可。

新增一个标准库模块的中文化示例（复制 数学.py 改两行就行）：

    模块 = {'随机': 'random'}
    成员 = {'随机': {'随机整数': 'randint', '选择': 'choice'}}
"""

