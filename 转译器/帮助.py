def _宽(文本: str) -> int:
    return sum(2 if unicodedata.east_asian_width(字) in ('W', 'F') else 1 for 字 in 文本)


def _补(文本: str, 宽: int) -> str:
    return 文本 + ' ' * max(0, 宽 - _宽(文本))


def _折行(名字们, 宽: int = 74) -> list[str]:
    """按显示宽度折行（不是按字数）"""
    行们: list[str] = []
    当前 = ''
    for 名 in 名字们:
        if _宽(当前 + 名 + '  ') > 宽 and 当前:
            行们.append(当前.rstrip())
            当前 = ''
        当前 += 名 + '  '
    if 当前.strip():
        行们.append(当前.rstrip())
    return 行们


def _卡片(词: str, 类别: str, 行们) -> str:
    """无边框卡片：第一行「词 · 类别」，后面 标签 + 内容"""
    标签宽 = 6
    出 = [f'{词} · {类别}']
    for 标签, 内容 in 行们:
        if not 内容:
            continue
        出.append(f'  {_补(标签, 标签宽)}{内容[0]}')
        for 续 in 内容[1:]:
            出.append('  ' + ' ' * 标签宽 + 续)
    return '\n'.join(出)


def _同义(词: str, 规则: dict) -> list[str]:
    """同一个 Python 目标还有哪些中文写法"""
    for 表名 in ('关键字', '内建', '异常'):
        表 = 规则.get(表名) or {}
        英文 = 表.get(词)
        if 英文 is None:
            continue
        别的 = [中 for 中, 英 in 表.items() if 英 == 英文 and 中 != 词]
        return 别的
    return []


def _糖锚点(规则: dict) -> dict[str, int]:
    """句式糖没有名字，用锚点词登记「这是第几条糖」"""
    结果: dict[str, int] = {}
    for 序号, 条 in enumerate(规则.get('语法糖') or [], 1):
        模式 = 条[0]
        for 锚 in ('否则如果', '如果', '否则', '对于', '遍历', '只要', '当', '重复执行',
                   '重复', '直到', '捕获', '定义函数', '尝试执行', '无论如何',
                   '等待', '把', '将', '给', '设', '输出', '打印'):
            if 锚 in 模式:
                结果.setdefault(锚, 序号)
    return 结果


