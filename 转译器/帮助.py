def _源码位置(函数, 帧) -> str:
    """按 co_firstlineno 回读 .bridge 原文（转译器承诺行号逐行对应，所以对得上）"""
    代码 = getattr(函数, '__code__', None)
    路径 = (帧.f_globals.get('__file__') if 帧 is not None else None)
    if not 代码 or not 路径:
        return ''
    行号 = getattr(代码, 'co_firstlineno', 0)
    try:
        行们 = open(路径, encoding='utf-8-sig').read().splitlines()
    except OSError:
        return ''
    if 0 < 行号 <= len(行们):
        return f'{路径} 第 {行号} 行：{行们[行号 - 1].strip()[:70]}'
    return ''


def _用户(词: str, 帧) -> str | None:
    if 帧 is None:
        return None
    # 模块顶层 exec 时 f_locals 就是 f_globals，别把它叫成"局部"
    候选 = []
    if 帧.f_locals is not 帧.f_globals:
        候选.append(('局部', 帧.f_locals))
    候选.append(('全局', 帧.f_globals))
    for 作用域, 容器 in 候选:
        if 词 not in 容器:
            continue
        值 = 容器[词]
        if callable(值) and not isinstance(值, type):
            import inspect

            try:
                签名 = f'{词}{inspect.signature(值)}'
            except (TypeError, ValueError):
                签名 = f'{词}(…)'
            行们 = [('种类', ['你定义的函数']), ('签名', [签名])]
            文档 = getattr(值, '__doc__', None)
            if 文档:
                行们.append(('说明', str(文档).strip().splitlines()))
            位置 = _源码位置(值, 帧)
            if 位置:
                行们.append(('位置', [位置]))
            行们.append(('调用', [f'{词}(…)    在{作用域}作用域里可用']))
            return _卡片(词, '你定义的东西', 行们)

        if isinstance(值, type):
            return _卡片(词, '你定义的东西',
                        [('种类', ['你定义的类']),
                         ('用法', [f'{词}(<参数>)    → 造一个对象'])])

        行们 = [('种类', [f'变量（{作用域}作用域）']),
                ('类型', [type(值).__name__]),
                ('值', [str(值)[:120] + ('…' if len(str(值)) > 120 else '')])]
        try:
            if not isinstance(值, (str, bytes)) and hasattr(值, '__len__'):
                行们.append(('长度', [str(len(值))]))
        except TypeError:
            pass
        return _卡片(词, '你定义的东西', 行们)
    return None


