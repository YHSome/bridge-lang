def _自动(词: str, 规则: dict) -> str | None:
    for 类别 in ('关键字', '内建', '异常'):
        表 = 规则.get(类别) or {}
        if 词 in 表:
            同义 = _同义(词, 规则)
            行们 = [('作用', [f'等价 Python 的 {表[词]}']), ('语法', [f'{词} …'])]
            if 同义:
                行们.insert(1, ('同义', [' / '.join(同义)]))
            return _卡片(词, 类别, 行们)

    英文方法 = (规则.get('方法') or {}).get(词)
    if 英文方法 is not None:
        同义 = [中 for 中, 英 in (规则.get('方法') or {}).items()
                if 英 == 英文方法 and 中 != 词]
        行们 = [('作用', [f'等价 Python 的 .{英文方法}()'])]
        if 同义:
            行们.append(('同义', [' / '.join(同义)]))
        行们.append(('注意', ['只写在点号后面：<对象>.' + 词 + '()']))
        return _卡片(词, '方法', 行们)

    模块 = (规则.get('模块') or {}).get(词)
    if 模块 is not None:
        成员 = (规则.get('成员') or {}).get(词) or {}
        行们 = [('作用', [f'等价 Python 的 {模块}']), ('用法', [f'导入 {词}'])]
        if 成员:
            行们.append(('成员', _折行([f'{中}→{英}' for 中, 英 in 成员.items()], 66)))
        return _卡片(词, '模块', 行们)

    if '.' in 词:
        头, _, 尾 = 词.partition('.')
        模块名 = (规则.get('模块') or {}).get(头, 头)
        成员表 = (规则.get('成员') or {}).get(头) or {}
        if 尾 in 成员表:
            return _卡片(词, f'成员（{模块名}）', [('作用', [f'等价 {模块名}.{成员表[尾]}'])])
        英文方法 = (规则.get('方法') or {}).get(尾)
        if 英文方法 is not None:
            对象说明 = (规则.get('内建') or {}).get(头) or (规则.get('模块') or {}).get(头) or 头
            return _卡片(词, '对象方法', [
                ('作用', [f'等价 Python 的 .{英文方法}()']),
                ('对象', [f'「{头}」= {对象说明}']),
                ('注意', ['方法只在点号后面生效；光写「' + 尾 + '」是另一张表的事']),
            ])
        if 头 in 手写:
            手 = 手写[头]
            return _卡片(词, f'{手["类别"]}·成员', [
                ('对象', [f'「{头}」{手["作用"]}']),
                ('可用', [f'{头}.{尾}(…)   —— 具体方法见 `{头}?`']),
            ])
    return None


